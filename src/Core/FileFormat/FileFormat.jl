"""
    POSCAR <: FileFormat

`POSCAR` is the input file of [VASP](https://vasp.at/wiki/POSCAR), containing the unit cell structure.

# Reading
    read(path::AbstractString, ::Type{POSCAR}; period::Vector{Bool}=[true, true, true]) -> Cell
    read(io::IO, ::Type{POSCAR}; period::Vector{Bool}=[true, true, true]) -> Cell

Read a unit cell from a `POSCAR` file or stream.

**Returns**:
- `Cell`: The unit cell structure (see [`Cell`](@ref)).

**Keyword arguments**:
- `period=[true, true, true]`: Periodicity along the three lattice vector directions. 
Each element can be `true`/`1` (periodic) or `false`/`0` (non‑periodic).

# Writing
    write(path::AbstractString, cell::Cell, ::Type{POSCAR}; mode="w", comment="", format::String="Cartesian")
    write(io::IO, cell::Cell, ::Type{POSCAR}; comment="", format::String="Cartesian")

Write a unit cell to a `POSCAR` file or stream.

**Arguments**:
- `cell::Cell`: The unit cell to write (see [`Cell`](@ref)).
- `format::String="Cartesian"`: Coordinate format; can be `"Cartesian"` or `"Direct"`.

See also [`FileFormat`](@ref), [`Cell`](@ref).
"""
struct POSCAR <: FileFormat end
"""
    epsmat_yambo <: FileFormat

Dielectric matrix calculated by [Yambo](https://wiki.yambo-code.eu/wiki/index.php?title=Main_Page).

# Reading
    read(epsfolder::AbstractString, ::Type{epsmat_yambo};
         SAVE::AbstractString=joinpath(dirname(epsfolder), "SAVE"),
         format::Symbol=:netcdf4,
         suffix::Union{AbstractString,Nothing}=nothing,
         ωindex::Union{Integer,AbstractVector{<:Integer}}=1,
         qgrid_atol::Real=1e-6,
         qgrid::Union{MonkhorstPack,Nothing}=nothing) -> DielectricPWBasis

Read dielectric matrix data from `epsfolder` (the directory containing the Yambo output files), 
requiring the `SAVE` folder.

**Returns**:
- [`DielectricPWBasis`](@ref): An object holding the dielectric function in plane-wave basis.

**Keyword arguments**:
- `SAVE::AbstractString`: Path to the `SAVE` folder (only `SAVE/ns.db1` is currently used).
- `format::Symbol`: File format passed to 
[`NCDataset`](https://juliageo.org/NCDatasets.jl/stable/dataset/#NCDatasets.NCDataset).
- `suffix::Union{AbstractString,Nothing}`: Suffix of the dielectric‑matrix files in `epsfolder` (e.g., `"em1s"`, `"pp"`, `"Xmpa"`, or `"em1d"`). The files are `ndb.\$(suffix)` and `ndb.\$(suffix)_fragment_\$(iq)`. If `nothing`, the suffix is auto‑detected.
- `ωindex::Union{Integer,AbstractVector{<:Integer}}`: Frequency index (or indices) to extract.
- `qgrid_atol::Real`: Tolerance for converting floating‑point q‑points to fractions, used to determine the q‑grid size.
- `qgrid::Union{MonkhorstPack,Nothing}`: Explicit q‑grid; if `nothing`, it is deduced from the irreducible q‑points with `qgrid_atol`.

See also [`FileFormat`](@ref), [`MonkhorstPack`](@ref), [`DielectricPWBasis`](@ref).
"""
struct epsmat_yambo <: FileFormat end
