"""
    abstract type FileFormat

Subtypes of `FileFormat` represent different file formats and 
support reading from and writing to files.

    read(path::AbstractString, ::Type{T}; kwargs...) where {T<:FileFormat}
    write(path::AbstractString, data, ::Type{T}; kwargs...) where {T<:FileFormat}

# Keyword arguments
The `write` function typically supports:
- `mode`: the write mode passed to [`Base.open`](https://docs.julialang.org/en/v1/base/io-network/#Base.open).
- `comment`: a comment line, usually the first line of the file.

See also [`FileFormatIO`](@ref).
"""
abstract type FileFormat end
"""
    BAND_dat <: FileFormat

File format compatible with the `BAND.dat` file generated by [VASPKIT](https://vaspkit.com/), storing band structure data.

# Reading
    read(path::AbstractString, ::Type{BAND_dat}; readkname::Bool=false) -> (band, kline)
    read(io::IO, ::Type{BAND_dat}; readkname::Bool=false) -> (band, kline)

Read a band structure from a `BAND.dat` file or stream.

**Returns**:
- `band::Matrix{<:Real}`: Energy values, size `(nband, nk)`.
- `kline::Kline`: k‑point path information. If `readkname=false`, returns a default [`Kline`](@ref).

**Keyword arguments**:
- `readkname::Bool=false`: If `true`, parse the `Kline` block from the file 
(only present if the file was written by this package with a non‑empty `kline`).

# Writing
    write(path::AbstractString, band, ::Type{BAND_dat}; mode="w", comment="", kline=Kline())
    write(io::IO, band, ::Type{BAND_dat}; comment="", kline=Kline())

Write band structure data to a `BAND.dat` file or stream.

**Arguments**:
- `band`: Energy values. Can be:
  - `AbstractMatrix{<:Real}` of size `(nband, nk)`,
  - a vector of real numbers (single k‑point, `nk=1`),
  - a vector of `Eigen` objects (one per k‑point, `nk = length(band)`),
  - a single `Eigen` object (one k‑point, `nk=1`).
- `kline::Kline=Kline()`: k‑point path to be written. If omitted, a default [`Kline`](@ref) is written.

See also [`FileFormat`](@ref), [`Kline`](@ref).
"""
struct BAND_dat <: FileFormat end
"""
Its format is the same as "PBAND.dat" generated by vaspkit, contains band structure and the projection value.

	write(path/io, pband, ::Type{PBAND_dat}; kline, projection)

- `pband`: should be a AbstractArray{<:Real};
- `kline`: a instance of [`Kline`](@ref) with a empty default.
- `projection`: Vector{String}

!!! note
	(nband, np+1, nk) = size(pband)
"""
struct PBAND_dat <: FileFormat end
