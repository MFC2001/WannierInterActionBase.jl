"""
    epsmat_bgw <: FileFormat

Dielectric matrix data in HDF5 format from [BerkeleyGW](https://berkeleygw.org/).

# Reading
    read(epsmat::AbstractString, ::Type{epsmat_bgw};
         vcoul::AbstractString=joinpath(dirname(epsmat), "vcoul"),
         eps0mat::AbstractString=joinpath(dirname(epsmat), "eps0mat.h5"),
         ωindex::Union{Integer,AbstractVector{<:Integer}}=1) -> DielectricPWBasis

Read dielectric matrices from BerkeleyGW HDF5 files (`epsmat.h5`, `eps0mat.h5`, and `vcoul`).

**Returns**:
- `DielectricPWBasis`: Object containing the dielectric function in a plane-wave basis.

**Keyword arguments**:
- `vcoul`: Path to the Coulomb potential file (default: `"vcoul"` in the same directory). Generated when `write_vcoul` is enabled in `epsilon.inp`
- `eps0mat`: Path to the static dielectric matrix (default: `"eps0mat.h5"` in the same directory).
- `ωindex`: Frequency index (or indices) to extract (default: `1`).

See also [`FileFormat`](@ref), [`DielectricPWBasis`](@ref).
"""
struct epsmat_bgw <: FileFormat end
"""
    vcoul_bgw <: FileFormat

