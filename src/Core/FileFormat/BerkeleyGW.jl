# Reading
    read(path::AbstractString, ::Type{vcoul_bgw}) -> vcoul_bgw
    read(io::IO, ::Type{vcoul_bgw}) -> vcoul_bgw

Read the Coulomb potential from a `vcoul` file or stream.

**Returns**:
- `vcoul_bgw`: Object containing the plane-wave Coulomb potential.

See also [`FileFormat`](@ref).
"""
