export QEpw, QEwfc, QEwfc_dat, QEwfc_hdf5, QE_xml_new, QE_wannier
"""
	QEpw <: FileFormat

The format of `pw.in` for [Quantum ESPRESSO](https://www.quantum-espresso.org/).

# Writing
	write(path/io, title::AbstractString, ::Type{QEpw}; kwargs...)

kwargs:
- `cell::Cell`: default is nothing;
- `kpoints`: default is nothing.
"""
struct QEpw <: FileFormat end
"""
    QEband <: FileFormat

The format of `<filband>.gnu` generated by `bands.x` of [Quantum ESPRESSO](https://www.quantum-espresso.org/).

# Reading
    read(io::IO, ::Type{QEband}) -> (kline, band)

Read band data from a `<filband>.gnu` file or stream.
`kline` is a Vector of Float64, `band` is a Matrix with size (nband, nk).

See also [`FileFormat`](@ref).
"""
struct QEband <: FileFormat end
"""
    QEwfc <: FileFormat

The format for wavefunction data in the `pwscf.save` directory of [Quantum ESPRESSO](https://www.quantum-espresso.org/).

# Reading
    read(path::AbstractString, ::Type{QEwfc}; kwargs...) -> QEwfc

Read wavefunction data from the `pwscf.save` directory, 
automatically selecting the appropriate format by the file suffix.

See also [`FileFormat`](@ref), [`QEwfc_dat`](@ref), [`QEwfc_hdf5`](@ref).
"""
struct QEwfc <: FileFormat
    ik::Int #index of kpoint.
    xk::ReducedCoordinates{Float64}
    ispin::Int #1: wospin or noncolin.
    gamma_only::Bool #only gamma.
    scalef::Float64
    ngw::Int #don't know!
    igwx::Int #the number of G or components
    npol::Int #1: wospin or collin, 2: noncollin.
    nbnd::Int
    rlattice::ReciprocalLattice{Float64}
    Glist::Vector{ReducedCoordinates{Int}}
    components::Matrix{ComplexF64} #[npol * igwx, nbnd]
end
"""
    QEwfc_dat <: FileFormat

Wavefunction data in the `wfc.dat` file in the `pwscf.save` directory of [Quantum ESPRESSO](https://www.quantum-espresso.org/).

# Reading
    read(path::AbstractString, ::Type{QEwfc_dat}; convert::String="native") -> QEwfc
	read(io::IO, ::Type{QEwfc_dat}; convert::String="native") -> QEwfc

Read a file or stream.

**Keyword arguments**:
- `convert::String="native"`: Byte‑order conversion flag passed to [`FortranFile`](https://juliadata.org/FortranFiles.jl/stable/files/#FortranFiles.FortranFile).

See also [`FileFormat`](@ref), [`QEwfc`](@ref).
"""
struct QEwfc_dat <: FileFormat end
"""
    QEwfc_hdf5 <: FileFormat

Wavefunction data in the `wfc.hdf5` file in the `pwscf.save` directory of [Quantum ESPRESSO](https://www.quantum-espresso.org/).

# Reading
    read(path::AbstractString, ::Type{QEwfc_hdf5}) -> QEwfc

Read the `wfc.hdf5` file.

See also [`FileFormat`](@ref), [`QEwfc`](@ref).
"""
struct QEwfc_hdf5 <: FileFormat end
"""
    QE_xml_new <: FileFormat

`data-file-schema.xml` file in the `pwscf.save` directory generated by [Quantum ESPRESSO](https://www.quantum-espresso.org/), 
containing structural and wavefunction metadata in XML format.

# Reading
    read(path::AbstractString, ::Type{QE_xml_new}; period=[1,1,1]) -> Dict{String,Any}

Read the XML file and return its parsed content as a dictionary.

**Keyword arguments**:
- `period=[1,1,1]`: Periodicity (as integers 1/0 or booleans) along the three lattice vectors, used to construct a `Cell` from the structure data.

See also [`FileFormat`](@ref).
"""
struct QE_xml_new <: FileFormat end
"""
    QE_wannier <: FileFormat

Compute Wannier functions in the plane-wave basis from `pwscf.save` data 
generated by [Quantum ESPRESSO](https://www.quantum-espresso.org/).

# Reading (standard)
    read(savefolder::AbstractString, ::Type{QE_wannier};
         bandindex::Vector{Vector{Int}}, u_matrix::Vector{Matrix{<:Number}},
         wfcspin::Union{Symbol,Nothing}=nothing,
         period::Vector{Int}=[1,1,1]) -> WannierPWKgrid

Read wavefunctions and apply the unitary transformation matrix to obtain Wannier functions.

**Keyword arguments**:
- `bandindex`: List of band indices for each k‑point (`[ik]` → `Vector{Int}`).
- `u_matrix`: Unitary matrix for each k‑point (`[ik]` → `Matrix{Number}`, size `(nband, nw)`).
- `wfcspin`: `:up` or `:dw` for spin‑polarized calculations; `nothing` for non‑spin‑polarized.
- `period`: Periodicity along lattice vectors (1/0 or true/false).

# Reading (shortcut)
    read(savefolder::AbstractString, chkdata::wannier90_chk, ::Type{QE_wannier};
         wfcspin=nothing, period=[1,1,1]) -> WannierPWKgrid

Use data from a `wannier90_chk` object to supply `bandindex` and `u_matrix`.

See also [`FileFormat`](@ref), [`WannierPWKgrid`](@ref), [`wannier90_chk`](@ref).
"""
struct QE_wannier <: FileFormat end
