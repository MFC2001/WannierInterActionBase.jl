"""
    wannier90_xsf{T<:Number} <: FileFormat

`<seedname>.xsf` file (XSF format) generated by [Wannier90](https://wannier.org/).

# Reading
    read(path::AbstractString, ::Type{wannier90_xsf}; period=[1,1,1]) -> wannier90_xsf{Float64}
    read(io::IO, ::Type{wannier90_xsf}; period=[1,1,1]) -> wannier90_xsf{Float64}

Read an XSF file or stream and return a `wannier90_xsf{Float64}` object.

**Keyword arguments**:
- `period=[1,1,1]`: Periodicity (as integers 1/0 or booleans) along the three lattice vectors, used to construct a [`Cell`](@ref).

# Writing
    write(path::AbstractString, wannier::wannier90_xsf{<:Number}, ::Type{wannier90_xsf}; mode="w", comment="", value=real)
    write(io::IO, wannier::wannier90_xsf{<:Number}, ::Type{wannier90_xsf}; comment="", value=real)

Write `wannier90_xsf` object to an XSF file or stream.

**Keyword arguments**:
- `value::Function=real`: Function applied to the grid values before writing (e.g., `real`, `imag`, or `abs`).

See also [`FileFormat`](@ref).
"""
struct wannier90_xsf{T<:Number} <: FileFormat
    cell::Cell{ReducedCoordinates{Float64}}
    origin::Vec3{Float64}
    grid_vecs::Mat3{Float64}
    grid_size::NTuple{3,Int}
    value::Array{T,3}
end
"""
    wannier90_xsf(value::AbstractArray{T,3}, range, cell::Cell) -> wannier90_xsf{T}

Construct a `wannier90_xsf` object from a 3D grid of values.

**Arguments**:
- `value`: Grid data, size `(Nx, Ny, Nz)`.
- `range`: Number of unit cells in each direction, e.g. `[3, 3, 3]`.

See also [`Cell`](@ref).
"""
function wannier90_xsf(value::AbstractArray{T,3}, range, cell::Cell{P}) where {T<:Number,P}
    lattice = parent(cell.lattice)
    origin = -lattice * [floor.(Int, (range .- 1) ./ 2)...]
    origin = Vec3(origin)

    grid_size = size(value)
    grid_vecs = Matrix{Float64}(undef, 3, 3)
    for i in 1:3
        grid_vecs[:, i] = lattice[:, i] * range[i] * (grid_size[i] - 1) / grid_size[i]
    end

    if P <: CartesianCoordinates
        cell = convert(cell)
    end

    return wannier90_xsf{T}(cell, origin, grid_vecs, grid_size, value)
end
