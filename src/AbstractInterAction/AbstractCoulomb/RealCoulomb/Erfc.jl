struct RealCoulombErfc <: RealCoulomb
    ϵ::Float64
    α::Float64
    coff::Float64
end
function (v::RealCoulombErfc)(r::AbstractVector{<:Real}; atol::Real=1e-10)::Float64
    r = norm(r)
    return r ≤ atol ? 0.0 : v.coff * erfc(v.α * r) / r
end
function (v::RealCoulombErfc)(r::Real; atol::Real=1e-10)::Float64
    signbit(r) && error("r should be positive")
    return r ≤ atol ? 0.0 : v.coff * erfc(v.α * r) / r
end
"""
	RealCoulomb(:erfc; ϵ::Real=1, α::Real=0.0) -> RealCoulombErfc

Calculate the difference between Coulomb potential generated by a point charge and a charge of Gaussian distribution in real space:

```math
V(r) = \\frac{e²}{4πϵ₀ϵ} \\frac{erfc(α|r|)}{|r|}
```

unit: r(Å), V(eV), α(1/Å), ϵ(dimensionless).

# Example

```julia
julia> V = RealCoulomb(:erfc; ϵ = 1.5, α = 1)
julia> r = [1.0, 0.0, 0.0] # or r = 1.0
julia> V(r)
julia> V(0.01; atol = 0.1) == 0
true
```
"""
function RealCoulomb(::Val{:erfc}; ϵ::Real=1.0, α::Real=0.0, atol::Real=1e-10)
    @assert ϵ > 0 "ϵ should be positive"
    @assert α > 0 "α should be positive"
    if α ≤ atol
        return RealCoulomb(Val(:point); ϵ, α)
    else
        coff = CoulombScale / ϵ
        return RealCoulombErfc(ϵ, α, coff)
    end
end
