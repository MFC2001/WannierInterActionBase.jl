struct ReciprocalCoulombKeldysh <: ReciprocalCoulomb
    r₀::Float64
    ϵ₁::Float64
    ϵ₂::Float64
    S::Float64
    coff::Float64
end
function (v::ReciprocalCoulombKeldysh)(k::AbstractVector{<:Real}; atol::Real=1e-10)::Float64
    k = sqrt(k ⋅ k)
    return k ≤ atol ? 0.0 : v.coff / (1 + v.r₀ * k) / k
end
function (v::ReciprocalCoulombKeldysh)(k::Real; atol::Real=1e-10)::Float64
    signbit(k) && error("k should be positive")
    return k ≤ atol ? 0.0 : v.coff / (1 + v.r₀ * k) / k
end
function (v::ReciprocalCoulombKeldysh)(::Val{:k²}, k²; atol::Real=1e-10)::Float64
    signbit(k²) && error("k² should be positive")
    return k² ≤ atol ? 0.0 : begin
        k = sqrt(k²)
        v.coff / (1 + v.r₀ * k) / k
    end
end
function (v::ReciprocalCoulombKeldysh)(::Val{:kscale}, k::AbstractVector{<:Real})::Float64
    k = sqrt(k ⋅ k)
    return v.coff / (1 + v.r₀ * k)
end
function (v::ReciprocalCoulombKeldysh)(::Val{:kscale}, k::Real)::Float64
    signbit(k) && error("k should be positive")
    return v.coff / (1 + v.r₀ * k)
end
function (v::ReciprocalCoulombKeldysh)(::Val{:taylor_0})::Float64
    return - v.coff * v.r₀
end
function (v::ReciprocalCoulombKeldysh)(::Val{:head}, nk::Integer)::Float64
    signbit(nk) && error("nk should be positive")
    NS = nk * v.S
    qsz = sqrt(4π / NS)
    return v.coff * NS * _log1p_div_x(v.r₀ * qsz) * qsz / 2π
end
function (v::ReciprocalCoulombKeldysh)(::Val{:head}, rlattice::ReciprocalLattice, kgrid::Union{AbstractVector,Tuple},
    zidx::Integer=findfirst(nk->nk == 1, kgrid))::Float64
    xyidx = setdiff(1:3, zidx)
    xyidx = SVector{2,Int}(xyidx[1], xyidx[2])
    rlattice = SMatrix{2,2}(rlattice[xyidx, xyidx])
    kgrid = kgrid[xyidx]
    return v(Val(:head), rlattice, kgrid)
end
function (v::ReciprocalCoulombKeldysh)(::Val{:head}, rlattice::AbstractMatrix, kgrid::Union{AbstractVector,Tuple})::Float64
    all(signbit, kgrid) && error("nk should be positive")
    minirlattice = hcat(rlattice[1:2, 1] ./ kgrid[1], rlattice[1:2, 2] ./ kgrid[2])
    miniFBZ = WignerSeitz(minirlattice)
    return v(Val(:head), miniFBZ, prod(kgrid))
end
function (v::ReciprocalCoulombKeldysh)(::Val{:head}, miniFBZ::HalfspaceConvexPolyhedron, nk::Integer)::Float64
    signbit(nk) && error("nk should be positive")

    qsz2 = minimum(miniFBZ.offsets) / 2
    qsz = sqrt(qsz2)

    a = Vector{Float64}(undef, 2)
    b = Vector{Float64}(undef, 2)
    for i in 1:2
        (a[i], b[i]) = extrema(k -> k[i], miniFBZ.normals)
    end

    function integrand(k)
        k² = k[1] * k[1] + k[2] * k[2]
        k² < qsz2 && return 0.0
        k ∈ miniFBZ && begin
            k = sqrt(k²)
            return 1 / (1 + v.r₀ * k) / k
        end
        return 0.0
    end

    (result, err) = hcubature(integrand, a, b; norm=abs, rtol=1e-8, atol=1e-10)
    result_circle = 2π * qsz * _log1p_div_x(v.r₀ * qsz)

    NS = nk * v.S
    return v.coff * (result + result_circle) * NS / (2π)^2
end
function _log1p_div_x(x::Real)
    x < 0 && throw(DomainError(x, "domain is x ≥ 0"))
    iszero(x) && return one(float(x))
    return log1p(x) / x
end
"""
	ReciprocalCoulomb(:keldysh; r₀::Real = 1, ϵ₁::Real = 1, ϵ₂::Real = 1, S::Real = 1) -> ReciprocalCoulombKeldysh

Calculate Coulomb potential generated by a point charge in 2D in reciprocal space:

```math
V(k) = \\frac{e²}{2Aϵ₀ϵdS} \\frac{1}{k(1+r₀k)}
ϵd = (ϵ₁ + ϵ₂) / 2
```

unit: k(1/Å), V(eV), r₀(Å), S(Å²), ϵ₁(dimensionless), ϵ₂(dimensionless).

# Example

```julia
julia> V = ReciprocalCoulomb(:keldysh; r₀ = 1, S = 10)
julia> k = [1.0, 0.0, 0.0] # or k = 1.0
julia> V(k)
```

We provide a method to calculate the head value:

```math
V(head) = \\frac{NS}{(2π)²} \\int_{0}^{q_{sz}} V(k) 2πk dk , 
πq_{sz}^2 = \\frac{(2π)²}{NS}
```

```julia
julia> V(:head, N)
```
"""
function ReciprocalCoulomb(::Val{:keldysh}; r₀::Real=1, ϵ₁::Real=1, ϵ₂::Real=1, S::Real=1)
    @assert r₀ ≥ 0 "r₀ should be positive"
    @assert ϵ₁ > 0 "ϵ₁ should be positive"
    @assert ϵ₂ > 0 "ϵ₂ should be positive"
    @assert S > 0 "S should be positive"
    ϵd = (ϵ₁ + ϵ₂) / 2
    coff = CoulombScale * 2π / (S * ϵd)
    return ReciprocalCoulombKeldysh(r₀, ϵ₁, ϵ₂, S, coff)
end
